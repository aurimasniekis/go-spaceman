package api

import (
	"context"
	"net/http"

	"github.com/danielgtaylor/huma/v2"

	"github.com/aurimasniekis/go-spaceman/internal/authz"
	"github.com/aurimasniekis/go-spaceman/internal/telegram/tgbot"
)

// TelegramBotRules are the authorization rules of the Telegram bot's connection (ADR-0083, plan §5.2): installation
// settings, so system:read to read and system:write with a step-up to change. The token is write-only.
var TelegramBotRules = map[string]Rule{
	"get-telegram-bot":    Global(authz.SystemRead),
	"put-telegram-bot":    StepUp(authz.SystemWrite),
	"delete-telegram-bot": StepUp(authz.SystemWrite),
}

type telegramBotOut struct {
	ETag string `header:"ETag"`
	Body *tgbot.Bot
}

// RegisterTelegramBot registers the Telegram bot connection operations.
func RegisterTelegramBot(svc *tgbot.Service) func(api huma.API, d *Deps) {
	return func(api huma.API, d *Deps) {
		tags := []string{"telegram"}
		huma.Register(api, huma.Operation{OperationID: "get-telegram-bot", Method: http.MethodGet, Path: "/telegram/bot",
			Summary: "The Telegram bot's connection and health (never its token)",
			Description: "The bot's settings, has_token and token_version (the token is never returned), the bot's ID and username from getMe, " +
				"and its live health: in webhook mode Telegram's getWebhookInfo (reused for 30 seconds). Needs system:read.",
			Tags: tags},
			func(ctx context.Context, _ *struct{}) (*telegramBotOut, error) {
				b, err := svc.Get(ctx)
				if err != nil {
					return nil, d.fail(ctx, "telegram.get_bot", err)
				}
				return &telegramBotOut{ETag: ETag(b.Version), Body: b}, nil
			})
		huma.Register(api, huma.Operation{OperationID: "put-telegram-bot", Method: http.MethodPut, Path: "/telegram/bot",
			Summary: "Configure the Telegram bot, or replace its configuration",
			Description: "Without If-Match this creates the configuration (bot_token required); with it, it replaces every field, and an empty " +
				"bot_token keeps the stored token. A new token is checked with Telegram's getMe before it is stored, sealed and never returned; " +
				"the webhook secret is generated by central and rotates with it. Configuring a different bot (another bot ID) revokes every " +
				"Telegram link, because their chats belong to the old bot; a new token of the same bot keeps them. Then central reconfigures " +
				"the running bot (commands, menu button, setWebhook or polling); a failure there is reported in health, not as an error. " +
				"The Bot API's address is not settable here (central's configuration file only). Needs system:write and a step-up.",
			Tags: tags},
			func(ctx context.Context, in *struct {
				IfMatch
				Body tgbot.Input
			}) (*telegramBotOut, error) {
				v, err := optionalVersion(in.IfMatch)
				if err != nil {
					return nil, d.fail(ctx, "telegram.put_bot", err)
				}
				b, err := svc.Put(ctx, Actor(ctx), v, in.Body)
				if err != nil {
					return nil, d.fail(ctx, "telegram.put_bot", err)
				}
				return &telegramBotOut{ETag: ETag(b.Version), Body: b}, nil
			})
		huma.Register(api, huma.Operation{OperationID: "delete-telegram-bot", Method: http.MethodDelete, Path: "/telegram/bot",
			Summary: "Remove the Telegram bot's configuration",
			Description: "Removes the webhook and the stored token: Telegram is off. Links stay, and resume if the same bot is configured again. " +
				"Needs system:write and a step-up.",
			Tags: tags, DefaultStatus: http.StatusNoContent},
			func(ctx context.Context, in *IfMatch) (*struct{}, error) {
				v, err := in.Version()
				if err != nil {
					return nil, d.fail(ctx, "telegram.delete_bot", err)
				}
				if err := svc.Delete(ctx, Actor(ctx), v); err != nil {
					return nil, d.fail(ctx, "telegram.delete_bot", err)
				}
				return &struct{}{}, nil
			})
	}
}
