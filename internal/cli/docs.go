const docsHeader = "<!-- Generated by `spaceman docs cli` (make cli-docs) from the command definitions. Do not edit. -->\n\n"

// GenerateDocs renders the CLI reference for VitePress: index.md (global flags, exit codes, every command) and one
// page per top-level command. It returns the file contents by name; WriteDocs writes them.
func GenerateDocs(root *cobra.Command) map[string][]byte {
	files := map[string][]byte{}
	var idx bytes.Buffer
	idx.WriteString(docsHeader)
	idx.WriteString("# Command-line reference\n\n")
	idx.WriteString("`spaceman` runs the control plane (`serve`), its offline administration (`admin`, `keys`, `backup`) and a remote client\n")
	idx.WriteString("for the administrative API. The remote commands are described in [the CLI guide](../../operators/cli); this reference is\n")
	idx.WriteString("generated from the command definitions, so it always matches the binary. Every remote command names the\n")
	idx.WriteString("[API operations](../api) it calls.\n\n")
	idx.WriteString("## Global flags\n\nEvery command accepts these.\n\n")
	idx.WriteString(flagTable(root.PersistentFlags()))
	idx.WriteString("\n## Exit codes\n\n| Code | Meaning |\n|---|---|\n")
	for _, r := range [][2]string{
		{"0", "success"},
		{"1", "usage: bad flags or arguments, unreadable input files, local failures"},
		{"2", "API error (other statuses, an unwanted final state such as a failed relocation or a broken audit chain) or the server could not be reached"},
		{"3", "conflict: 409, 412 or 428 (the object changed since it was read, already exists, or the operation's precondition failed)"},
		{"4", "not found: 404 (also a space you cannot read)"},
		{"5", "authentication or authorization: 401, 403, or no usable token"},
	} {
		fmt.Fprintf(&idx, "| `%s` | %s |\n", r[0], r[1])
	}
	idx.WriteString("\n## Commands\n\n| Command | Description |\n|---|---|\n")
	for _, c := range visible(root) {
		fmt.Fprintf(&idx, "| [`%s`](./%s) | %s |\n", c.CommandPath(), c.Name(), escapeMD(c.Short))
		var page bytes.Buffer
		page.WriteString(docsHeader)
		fmt.Fprintf(&page, "# %s\n\n", c.CommandPath())
		writeCommand(&page, c, true)
		files[c.Name()+".md"] = page.Bytes()
	}
	files["index.md"] = idx.Bytes()
	return files
}

// WriteDocs writes the reference into dir, removing generated pages that no longer exist.
func WriteDocs(root *cobra.Command, dir string) error {
	files := GenerateDocs(root)
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // site sources are world-readable
		return err
	}
	old, _ := filepath.Glob(filepath.Join(dir, "*.md"))
	for _, p := range old {
		if _, ok := files[filepath.Base(p)]; !ok {
			if b, err := os.ReadFile(p); err == nil && bytes.HasPrefix(b, []byte(docsHeader[:40])) { //nolint:gosec // a page in the output directory
				if err := os.Remove(p); err != nil {
					return err
				}
			}
		}
	}
	for name, b := range files {
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil { //nolint:gosec // site sources are world-readable
			return err
		}
	}
	return nil
}

func visible(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, ch := range c.Commands() {
		if ch.Hidden || ch.Name() == "help" || ch.Name() == "completion" {
			continue
		}
		out = append(out, ch)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name() < out[j].Name() })
	return out
}

func writeCommand(b *bytes.Buffer, c *cobra.Command, top bool) {
	if !top {
		fmt.Fprintf(b, "## %s\n\n", c.CommandPath())
	}
	if c.Short != "" {
		b.WriteString(escapeMD(c.Short) + ".\n\n")
	}
	if c.Long != "" {
		b.WriteString(escapeMD(c.Long) + "\n\n")
	}
	if c.Runnable() {
		// UseLine adds [flags] only once persistent flags were merged, which depends on traversal order.
		fmt.Fprintf(b, "```sh\n%s [flags]\n```\n\n", strings.TrimSuffix(c.UseLine(), " [flags]"))
	}
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "Aliases: `%s`.\n\n", strings.Join(c.Aliases, "`, `"))
	}
	if ops := c.Annotations[annOps]; ops != "" {
		parts := splitComma(ops)
		for i, p := range parts {
			parts[i] = "`" + p + "`"
		}
		fmt.Fprintf(b, "API: %s ([HTTP API](../api)).\n\n", strings.Join(parts, ", "))
	}
	if c.Example != "" {
		fmt.Fprintf(b, "Example:\n\n```sh\n%s\n```\n\n", strings.TrimSpace(c.Example))
	}
	if t := flagTable(c.LocalNonPersistentFlags()); t != "" {
		b.WriteString(t + "\n")
	}
	children := visible(c)
	if len(children) > 0 && c.HasSubCommands() {
		b.WriteString("| Subcommand | Description |\n|---|---|\n")
		for _, ch := range children {
			fmt.Fprintf(b, "| [`%s`](#%s) | %s |\n", ch.CommandPath(), anchor(ch.CommandPath()), escapeMD(ch.Short))
		}
		b.WriteString("\n")
	}
	for _, ch := range children {
		writeCommand(b, ch, false)
	}
}

func anchor(s string) string { return strings.ReplaceAll(strings.ToLower(s), " ", "-") }

func flagTable(fs *pflag.FlagSet) string {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		def := ""
		switch f.Value.Type() {
		case "bool":
			if f.DefValue != "false" {
				def = "`" + f.DefValue + "`"
			}
		case "stringArray", "stringSlice":
			if f.DefValue != "[]" {
				def = "`" + f.DefValue + "`"
			}
		default:
			if f.DefValue != "" && f.DefValue != "0" && f.DefValue != "0s" {
				def = "`" + f.DefValue + "`"
			}
		}
		typ := f.Value.Type()
		switch typ {
		case "stringArray":
			typ = "string, repeatable"
		case "int64", "int":
			typ = "integer"
		}
		rows = append(rows, fmt.Sprintf("| %s | %s | %s | %s |", name, typ, def, escapeMD(f.Usage)))
	})
	if len(rows) == 0 {
		return ""
	}
	return "| Flag | Type | Default | Description |\n|---|---|---|---|\n" + strings.Join(rows, "\n") + "\n"
}

// escapeMD makes text safe for a Markdown table cell in VitePress: no raw HTML (angle brackets would be parsed as Vue
// components), no pipes, no Vue interpolation; code spans are kept.
func escapeMD(s string) string {
	var b strings.Builder
	inCode := false
	for _, r := range s {
		switch {
		case r == '`':
			inCode = !inCode
			b.WriteRune(r)
		case r == '|':
			b.WriteString(`\|`)
		case r == '\n':
			b.WriteRune(' ')
		case !inCode && r == '<':
			b.WriteString("&lt;")
		case !inCode && r == '>':
			b.WriteString("&gt;")
		case !inCode && r == '{':
			b.WriteString("&#123;")
		case !inCode && r == '}':
			b.WriteString("&#125;")
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}
