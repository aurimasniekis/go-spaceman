// AutoExcluded reports whether an operation's rule keeps it from Telegram whatever Ops says, and why. The API refuses
// a Telegram principal on these rules too (authorizeOps): public operations other than the Mini App's session exchange,
// step-up, and personal Session or UserOnly operations that aren't Telegram self-service.
func AutoExcluded(r api.Rule) (string, bool) {
	switch {
	case r.Public:
		return "public operation: only the session exchange (class exchange) is served to Telegram", true
	case r.Reauth || r.MFA:
		return "needs a recent re-authentication or a second factor (step-up): web only", true
	case r.TelegramSelf:
		return "", false
	case r.UserOnly:
		return "acts on the caller's own user account", true
	case r.Session && !r.Filtered:
		return "a signed-in principal's own view (session rule)", true
	}
	return "", false
}

// Classify returns an operation's Telegram class: Ops' entry, else excluded when AutoExcluded, else false
// (unclassified). Ops may name an auto-excluded public operation only as the exchange.
func Classify(id string, r api.Rule) (api.TelegramClass, bool) {
	if c, ok := Ops[id]; ok {
		return c, true
	}
	if _, ok := AutoExcluded(r); ok {
		return api.TelegramExcluded, true
	}
	return "", false
}
