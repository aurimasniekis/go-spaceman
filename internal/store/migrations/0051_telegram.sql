-- 0051_telegram: every table of the Telegram bot and Mini App (ADR-0083, SM-TG-*), created at once so later Telegram
-- tasks add no migrations.
--
-- MERGE ORDER: this migration needs 0050 (the usage-limit stack) on main first. Central refuses to open a database
-- whose version is above a migration it never applied (ErrMissingMigrations), so a central that ran 0051 before 0050
-- existed could not start once 0050 ships. Never release this without 0050 below it.
--
-- Secrets (the bot token, the webhook secret) are sealed with the keyring's credential purpose and are never readable
-- through any API. Telegram's own state writes no change-feed entries (a NULL-space change would reach every watch
-- stream): caches are invalidated over the in-process eventbus instead.

-- +goose Up

-- The bot's connection: one bot per central. A missing row means Telegram is off.
CREATE TABLE telegram_bot (
  singleton                 INTEGER PRIMARY KEY CHECK (singleton = 1),
  -- Learnt from getMe (0 until then). A different bot ID than before revokes every link: the chats belong to the old bot.
  bot_id                    INTEGER NOT NULL DEFAULT 0,
  username                  TEXT NOT NULL DEFAULT '',
  token_enc                 BLOB NOT NULL,
  -- Incremented whenever a new token is written (the write-only version counter).
  token_version             INTEGER NOT NULL DEFAULT 1,
  -- setWebhook's secret_token, generated by central and rotated with every token set.
  webhook_secret_enc        BLOB NOT NULL,
  -- The last path segment of POST /telegram/webhook/<hook_id>: 16 random bytes as unpadded base64url.
  hook_id                   TEXT NOT NULL CHECK (length(hook_id) = 22),
  mode                      TEXT NOT NULL DEFAULT 'webhook' CHECK (mode IN ('webhook', 'polling')),
  enabled                   INTEGER NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
  -- The Mini App's own cookieless host ('' = Mini App off).
  miniapp_host              TEXT NOT NULL DEFAULT '',
  -- JSON array of CIDRs the webhook accepts requests from (empty = no source check).
  webhook_ip_allowlist_json TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(webhook_ip_allowlist_json)),
  created_at                INTEGER NOT NULL,
  created_by                TEXT NOT NULL,
  updated_at                INTEGER NOT NULL,
  updated_by                TEXT NOT NULL,
  version                   INTEGER NOT NULL DEFAULT 1
) STRICT;

-- Policy and defaults, kept apart from the bot row so a policy change never touches the sealed token. A missing row
-- means the built-in defaults.
CREATE TABLE telegram_settings (
  singleton     INTEGER PRIMARY KEY CHECK (singleton = 1),
  settings_json TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(settings_json)),
  updated_at    INTEGER NOT NULL,
  updated_by    TEXT NOT NULL,
  version       INTEGER NOT NULL DEFAULT 1
) STRICT;

-- Single-use link codes: only the SHA-256 of the code is stored. Expired rows are pruned by retention.
CREATE TABLE telegram_link_codes (
  code_hash              BLOB PRIMARY KEY CHECK (length(code_hash) = 32),
  user_id                TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- How the session that created the code signed in (password, oidc, …).
  created_session_method TEXT NOT NULL,
  created_at             INTEGER NOT NULL,
  expires_at             INTEGER NOT NULL,
  state                  TEXT NOT NULL DEFAULT 'new' CHECK (state IN ('new', 'redeemed', 'confirmed', 'cancelled', 'expired')),
  -- The Telegram identity that redeemed the code with /start (NULL until redeemed).
  redeemed_tg_user_id    INTEGER,
  redeemed_tg_username   TEXT NOT NULL DEFAULT '',
  redeemed_tg_name       TEXT NOT NULL DEFAULT '',
  redeemed_at            INTEGER,
  CHECK (state IN ('new', 'cancelled', 'expired') OR redeemed_tg_user_id IS NOT NULL)
) STRICT, WITHOUT ROWID;
CREATE INDEX telegram_link_codes_user ON telegram_link_codes (user_id);
CREATE INDEX telegram_link_codes_expiry ON telegram_link_codes (expires_at);

-- A Telegram user linked to a SpaceMan user. The link's capped grants are ordinary role grants of the subject
-- telegram:<link_id> in the grants table (the API-token path), so they need no table here.
CREATE TABLE telegram_links (
  id               TEXT PRIMARY KEY,
  user_id          TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- The bot the link belongs to (its private chat is with that bot).
  bot_id           INTEGER NOT NULL,
  tg_user_id       INTEGER NOT NULL,
  tg_username      TEXT NOT NULL DEFAULT '',
  tg_name          TEXT NOT NULL DEFAULT '',
  -- The private chat (equal to tg_user_id for private chats).
  chat_id          INTEGER NOT NULL,
  state            TEXT NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'suspended', 'blocked', 'revoked')),
  -- Confirmed from an SSO session: sso_until is that session's absolute expiry (SSO grants count only until then).
  via_sso          INTEGER NOT NULL DEFAULT 0 CHECK (via_sso IN (0, 1)),
  sso_until        INTEGER,
  max_role         TEXT NOT NULL DEFAULT 'operator' CHECK (max_role IN ('viewer', 'operator', 'admin')),
  -- JSON array of space IDs the link is narrowed to (empty = every space the cap allows).
  spaces_json      TEXT NOT NULL DEFAULT '[]' CHECK (json_valid(spaces_json)),
  current_space_id TEXT REFERENCES spaces (id) ON DELETE SET NULL,
  -- Topics mode: JSON object of space ID (and "needs") to message_thread_id.
  topics_json      TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(topics_json)),
  -- The user's own overrides only; effective prefs are the global defaults with these applied.
  prefs_json       TEXT NOT NULL DEFAULT '{}' CHECK (json_valid(prefs_json)),
  created_at       INTEGER NOT NULL,
  confirmed_at     INTEGER,
  reconfirm_due_at INTEGER,
  revoked_at       INTEGER,
  revoked_by       TEXT NOT NULL DEFAULT '',
  updated_at       INTEGER NOT NULL,
  version          INTEGER NOT NULL DEFAULT 1,
  CHECK (state <> 'revoked' OR revoked_at IS NOT NULL)
) STRICT, WITHOUT ROWID;
-- One live link per Telegram user. Links per SpaceMan user are bounded by the links_per_user setting (1–3), checked
-- when a link is confirmed.
CREATE UNIQUE INDEX telegram_links_tg_user ON telegram_links (tg_user_id) WHERE state <> 'revoked';
CREATE INDEX telegram_links_user ON telegram_links (user_id, state);

-- Messages the bot sent that it may edit later (card final state, reminders). Written in batches by the sender and
-- pruned by retention after 30 days.
CREATE TABLE telegram_messages (
  chat_id          INTEGER NOT NULL,
  message_id       INTEGER NOT NULL,
  link_id          TEXT REFERENCES telegram_links (id) ON DELETE CASCADE,
  -- The resource's space (NULL for cross-space messages such as the digest); a space purge removes its rows.
  space_id         TEXT REFERENCES spaces (id) ON DELETE CASCADE,
  kind             TEXT NOT NULL,
  resource_type    TEXT NOT NULL DEFAULT '',
  resource_id      TEXT NOT NULL DEFAULT '',
  resource_version INTEGER NOT NULL DEFAULT 0,
  created_at       INTEGER NOT NULL,
  PRIMARY KEY (chat_id, message_id)
) STRICT, WITHOUT ROWID;
CREATE INDEX telegram_messages_resource ON telegram_messages (resource_type, resource_id);
CREATE INDEX telegram_messages_created ON telegram_messages (created_at);
CREATE INDEX telegram_messages_link ON telegram_messages (link_id);
CREATE INDEX telegram_messages_space ON telegram_messages (space_id);

-- A space's Telegram settings. A space without a row, or with enabled = 0, is invisible to Telegram (opt-in per space).
CREATE TABLE space_telegram_settings (
  space_id           TEXT PRIMARY KEY REFERENCES spaces (id) ON DELETE CASCADE,
  enabled            INTEGER NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
  content_level      TEXT NOT NULL DEFAULT 'full' CHECK (content_level IN ('full', 'summary', 'off')),
  enforced_approvals TEXT NOT NULL DEFAULT 'web_only' CHECK (enforced_approvals IN ('web_only', 'confirm')),
  topics             INTEGER NOT NULL DEFAULT 0 CHECK (topics IN (0, 1)),
  terminal_watch     INTEGER NOT NULL DEFAULT 0 CHECK (terminal_watch IN (0, 1)),
  -- Group mode (phase 3): the forum supergroup bound to the space (NULL: none).
  group_chat_id      INTEGER UNIQUE,
  created_at         INTEGER NOT NULL,
  created_by         TEXT NOT NULL,
  updated_at         INTEGER NOT NULL,
  updated_by         TEXT NOT NULL,
  version            INTEGER NOT NULL DEFAULT 1
) STRICT, WITHOUT ROWID;

