// The configuration reference (site/reference/configuration.md) is generated from the configuration types, their doc
// comments and Default()/DefaultAgent() (SM-DOCS-005 reference drift). Regenerate with `make config-docs`.
var updateReference = flag.Bool("update", false, "rewrite site/reference/configuration.md")

const referencePath = "../../site/reference/configuration.md"

func TestConfigReferenceUpToDate(t *testing.T) {
	docs := fieldDocs(t, ".", "../obs")
	got := renderReference(t, docs)
	if *updateReference {
		if err := os.WriteFile(referencePath, []byte(got), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(referencePath)
	if err != nil {
		t.Fatalf("%v (run make config-docs)", err)
	}
	if string(want) != got {
		t.Fatalf("%s is out of date: run make config-docs", filepath.Clean(referencePath))
	}
}

// fieldDocs maps "Type.Field" and "Type" to their doc comments, from the non-test Go files in dirs.
func fieldDocs(t *testing.T, dirs ...string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for _, dir := range dirs {
		files, err := filepath.Glob(filepath.Join(dir, "*.go"))
		if err != nil {
			t.Fatal(err)
		}
		fset := token.NewFileSet()
		for _, f := range files {
			if strings.HasSuffix(f, "_test.go") {
				continue
			}
			af, err := parser.ParseFile(fset, f, nil, parser.ParseComments)
			if err != nil {
				t.Fatal(err)
			}
			for _, d := range af.Decls {
				gd, ok := d.(*ast.GenDecl)
				if !ok || gd.Tok != token.TYPE {
					continue
				}
				for _, s := range gd.Specs {
					ts := s.(*ast.TypeSpec)
					st, ok := ts.Type.(*ast.StructType)
					if !ok {
						continue
					}
					out[ts.Name.Name] = gd.Doc.Text()
					for _, fl := range st.Fields.List {
						for _, n := range fl.Names {
							out[ts.Name.Name+"."+n.Name] = fl.Doc.Text()
						}
					}
				}
			}
		}
	}
	return out
}

func renderReference(t *testing.T, docs map[string]string) string {
	t.Helper()
	var b strings.Builder
	b.WriteString(`<!-- Generated by internal/config TestConfigReferenceUpToDate from the configuration types and their defaults.
     Do not edit: run make config-docs. -->

# Configuration reference

Both programs read one YAML file (` + "`--config`" + `, or ` + "`SPACEMAN_CONFIG`" + ` / ` + "`SPACEMAN_AGENT_CONFIG`" + `) and then environment
overrides. Unknown keys and unknown override variables are rejected, so a typo stops the program instead of being
ignored. Every problem is reported at once. Secrets never go in the file: the KEK, TLS keys, S3 keys and Pulse
credentials are read from the files named here.

- **Central** (` + "`spaceman serve`" + `, ` + "`spaceman backup`" + `): overrides are ` + "`SPACEMAN_<PATH>`" + `, e.g. ` + "`SPACEMAN_HTTP_LISTEN=:8443`" + `. Lists are
  comma-separated. Variables of the node agent (` + "`SPACEMAN_AGENT_*`" + `) and of the command-line client
  (` + "`SPACEMAN_SERVER`" + `, ` + "`SPACEMAN_TOKEN`" + `, ` + "`SPACEMAN_TOKEN_FILE`" + `, ` + "`SPACEMAN_OUTPUT`" + `, ` + "`SPACEMAN_SPACE`" + `, ` + "`SPACEMAN_ALLOW_INSECURE_HTTP`" + `), of ` + "`spaceman-agent enroll`" + ` (` + "`SPACEMAN_ENROLL_TOKEN`" + `) and of the Terraform
  provider (` + "`SPACEMAN_ENDPOINT`" + `) are ignored.
- **Node agent** (` + "`spaceman-agent`" + `): overrides are ` + "`SPACEMAN_AGENT_<PATH>`" + `.
- **Durations** are Go duration strings: ` + "`30s`" + `, ` + "`15m`" + `, ` + "`24h`" + `.

Annotated examples: ` + "`deploy/examples/spaceman.example.yaml`" + `, ` + "`deploy/examples/spaceman.container.yaml`" + ` and
` + "`deploy/examples/agent.example.yaml`" + ` ([installation](/operators/install)). Limits set here are installation defaults;
spaces override them ([limits and budgets](/guide/limits)).

`)
	b.WriteString("## Central (`spaceman`)\n\n")
	renderStruct(t, &b, docs, reflect.ValueOf(Default()).Elem(), EnvPrefix)
	b.WriteString("## Node agent (`spaceman-agent`)\n\n")
	renderStruct(t, &b, docs, reflect.ValueOf(DefaultAgent()).Elem(), AgentEnvPrefix)
	return b.String()
}

type refRow struct{ key, def, env, doc string }

// renderStruct writes one table of the top-level scalar keys, then one section per nested block.
func renderStruct(t *testing.T, b *strings.Builder, docs map[string]string, v reflect.Value, prefix string) {
	t.Helper()
	var top []refRow
	type section struct {
		key  string
		typ  string
		doc  string
		rows []refRow
	}
	var sections []section
	tt := v.Type()
	for i := range tt.NumField() {
		f := tt.Field(i)
		key := yamlKey(f)
		fv := v.Field(i)
		if isBlock(fv) {
			s := section{key: key, typ: fv.Type().Name(), doc: docs[fv.Type().Name()]}
			collect(t, docs, fv, []string{key}, prefix, &s.rows)
			sections = append(sections, s)
			continue
		}
		top = append(top, row(t, docs, tt, f, fv, []string{key}, prefix))
	}
	writeTable(b, top)
	for _, s := range sections {
		fmt.Fprintf(b, "### `%s`\n\n", s.key)
		if d := oneLine(s.doc, s.typ); d != "" {
			b.WriteString(d + "\n\n")
		}
		writeTable(b, s.rows)
	}
}

func collect(t *testing.T, docs map[string]string, v reflect.Value, path []string, prefix string, rows *[]refRow) {
	t.Helper()
	tt := v.Type()
	for i := range tt.NumField() {
		f := tt.Field(i)
		p := append(append([]string(nil), path...), yamlKey(f))
		if fv := v.Field(i); isBlock(fv) {
			collect(t, docs, fv, p, prefix, rows)
		} else {
			*rows = append(*rows, row(t, docs, tt, f, fv, p, prefix))
		}
	}
}

func row(t *testing.T, docs map[string]string, owner reflect.Type, f reflect.StructField, fv reflect.Value, path []string, prefix string) refRow {
	t.Helper()
	d := oneLine(docs[owner.Name()+"."+f.Name], f.Name)
	if d == "" {
		t.Errorf("%s.%s (%s) has no doc comment; the configuration reference needs one", owner.Name(), f.Name, strings.Join(path, "."))
	}
	return refRow{key: strings.Join(path, "."), def: defaultText(fv), env: envName(prefix, path), doc: d}
}

func isBlock(v reflect.Value) bool {
	return v.Kind() == reflect.Struct && v.Type() != reflect.TypeFor[Duration]()
}

func yamlKey(f reflect.StructField) string { return strings.Split(f.Tag.Get("yaml"), ",")[0] }

func defaultText(v reflect.Value) string {
	switch {
	case v.Type() == reflect.TypeFor[Duration]():
		if v.Int() == 0 {
			return "`0`"
		}
		return "`" + Duration(v.Int()).D().String() + "`"
	case v.Kind() == reflect.String:
		if v.String() == "" {
			return "(empty)"
		}
		return "`" + v.String() + "`"
	case v.Kind() == reflect.Slice:
		if v.Len() == 0 {
			return "`[]`"
		}
	}
	return fmt.Sprintf("`%v`", v.Interface())
}

// oneLine turns a doc comment into one Markdown table cell, dropping the leading identifier that Go doc comments
// start with ("LeaseTTL is how long…" becomes "How long…").
func oneLine(s, name string) string {
	s = strings.Join(strings.Fields(s), " ")
	if rest, ok := strings.CutPrefix(s, name+" "); ok && rest != "" {
		rest = strings.TrimPrefix(rest, "is ")
		s = strings.ToUpper(rest[:1]) + rest[1:]
	}
	return strings.NewReplacer("|", "\\|", "<", "&lt;", ">", "&gt;").Replace(s)
}

func writeTable(b *strings.Builder, rows []refRow) {
	if len(rows) == 0 {
		return
	}
	b.WriteString("| Key | Default | Environment | Description |\n|---|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(b, "| `%s` | %s | `%s` | %s |\n", r.key, r.def, r.env, r.doc)
	}
	b.WriteString("\n")
}
